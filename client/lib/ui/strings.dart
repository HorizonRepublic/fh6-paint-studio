/// The interface's words, in the twelve languages the project ships.
///
/// A flat map per language rather than a code-generated bundle: this is one
/// screen with about seventy strings, and a missing key falling back to English
/// is better behaviour than a build that fails because a translation is late.
///
/// The locale list matches `internal/i18n` exactly, so a user who ran the old
/// studio finds their language here under the same name. The WORDING is new —
/// these are this interface's controls, not the previous one's.
library;

import 'package:flutter/widgets.dart';

class Lang {
  const Lang(this.code, this.endonym, this._values);

  final String code;
  final String endonym;
  final Map<String, String> _values;

  String get(String key) => _values[key] ?? _en[key] ?? key;

  /// Whether this language defines the key itself rather than borrowing the
  /// English one. Exposed for the completeness test: comparing the STRINGS
  /// cannot tell a fallback from a word that is genuinely the same in both
  /// languages, and "Export" is the same in half of them.
  bool has(String key) => _values.containsKey(key);

  /// Every key this language defines, for tests.
  Iterable<String> get keys => _values.keys;
}

