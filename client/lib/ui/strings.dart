/// Builds a catalogue from a list parallel to [_keys]. Positional rather than
/// keyed so a translation cannot silently omit an entry: a short list is a
/// compile-time length mismatch caught by the test, not a string that quietly
/// falls back to English in one language only.
Map<String, String> _cat(List<String> v) {
  assert(
    v.length == _keys.length,
    'catalogue has ${v.length} of ${_keys.length}',
  );
  return {for (var i = 0; i < _keys.length; i++) _keys[i]: v[i]};
}

