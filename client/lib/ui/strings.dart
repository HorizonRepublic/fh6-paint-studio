/// The same order the previous studio offered, so a returning user finds their
/// language where they left it.
final languages = <Lang>[
  Lang('en', 'English', _en),
  Lang('uk', 'Українська', _uk),
  Lang('de', 'Deutsch', _de),
  Lang('es', 'Español', _es),
  Lang('pt-BR', 'Português (BR)', _ptBR),
  Lang('fr', 'Français', _fr),
  Lang('pl', 'Polski', _pl),
  Lang('it', 'Italiano', _it),
  Lang('tr', 'Türkçe', _tr),
  Lang('zh-CN', '中文(简体)', _zhCN),
  Lang('ja', '日本語', _ja),
  Lang('ko', '한국어', _ko),
];

Lang langFor(String code) =>
    languages.firstWhere((l) => l.code == code, orElse: () => languages.first);

/// Picks a language from the OS locale on first run: an exact code first, then
/// the bare language, so `pt-PT` lands on Brazilian Portuguese rather than
/// English and `de-AT` on German.
Lang langForSystem(String systemLocale) {
  final tag = systemLocale.replaceAll('_', '-');
  for (final l in languages) {
    if (l.code.toLowerCase() == tag.toLowerCase()) return l;
  }
  final base = tag.split('-').first.toLowerCase();
  for (final l in languages) {
    if (l.code.split('-').first.toLowerCase() == base) return l;
  }
  return languages.first;
}

/// Makes the current language reachable from any widget without threading it
/// through every constructor, and rebuilds everything below when it changes.
class Strings extends InheritedWidget {
  const Strings({super.key, required this.lang, required super.child});

  final Lang lang;

  static Lang of(BuildContext context) {
    final s = context.dependOnInheritedWidgetOfExactType<Strings>();
    return s?.lang ?? languages.first;
  }

  @override
  bool updateShouldNotify(Strings old) => old.lang.code != lang.code;
}

/// `context.s('generate')` — short because it appears in every label.
extension StringsX on BuildContext {
  String s(String key) => Strings.of(this).get(key);
}
